"""Generate the .ipynb notebooks from their paired .py sources.

The .py file is the source of truth: it is what CI runs, what the tests
import against, and what code review reads. The .ipynb is a derived
artifact, regenerated by this script so the two cannot drift.

Why this lives in the repo rather than in someone's scratch directory:
it was originally a throwaway script, which meant every regeneration
depended on that file still existing. It didn't, twice — and both times
the notebooks silently kept a stale setup cell while the .py moved on.
A build step that only exists on one machine is not a build step.

Usage:
    python scripts/build_notebooks.py              # all notebooks
    python scripts/build_notebooks.py 04_generation # just one
    python scripts/build_notebooks.py --check      # verify, write nothing

The generated notebook:
  - has no outputs (a cell output can bake a leaked credential into git
    history permanently)
  - carries cell ids, which nbformat 4.5+ requires. They are the cell's
    position ("0", "1", ...), assigned here with no library involved —
    see the note in build() for why
  - replaces the .py's __file__-based path setup with a root finder that
    works wherever Jupyter was launched
"""
from __future__ import annotations

import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOKS = ROOT / "notebooks"

# The .py files locate the project with __file__, which is correct for a
# script and unavailable in a notebook. This replacement searches up and
# then down for a marker file, so it resolves whether Jupyter started
# inside notebooks/, at the project root, or in a parent folder holding
# several projects.
ROOT_FINDER = '''# Locate the project root without assuming where Jupyter was launched.
#
# Two wrong assumptions were made here before, each breaking a real
# workflow:
#
#   Path.cwd().parent   assumes the kernel started in notebooks/. Launch
#                       Jupyter from the project root and it resolves one
#                       level too high.
#   walking up only     assumes the kernel started at or below the
#                       project. Launch Jupyter from a folder holding
#                       several projects — a normal thing to do — and the
#                       project is BELOW cwd, so upward search never
#                       finds it.
#
# So: search up, then search down. The marker is a file unique to this
# project, not a generic name like src/ that a sibling project might
# also have.
_MARKER = Path("src") / "corpus" / "seed_articles.py"


def _find_project_root(start: Path) -> Path:
    start = start.resolve()

    for candidate in [start, *start.parents]:          # up
        if (candidate / _MARKER).is_file():
            return candidate

    for pattern in ("*", "*/*"):                       # then down, bounded
        found = sorted({m.parents[2]
                        for m in start.glob(f"{pattern}/{_MARKER.as_posix()}")})
        if len(found) == 1:
            return found[0]
        if len(found) > 1:
            names = ", ".join(p.name for p in found)
            raise RuntimeError(
                f"Found several candidate project roots below {start}: "
                f"{names}. Start Jupyter inside the one you want."
            )

    raise RuntimeError(
        f"Could not locate the project root from {start}. Expected to find "
        f"{_MARKER.as_posix()} at, above, or within two levels below it."
    )


PROJECT_ROOT = _find_project_root(Path.cwd())
sys.path.insert(0, str(PROJECT_ROOT))
import os
os.chdir(PROJECT_ROOT)          # so data/ and reports/ paths resolve'''

SECTION_BANNER = re.compile(r"^# ={5,}\n# ([A-Z]\..*?)\n# ={5,}$", re.M)
SUBSECTION_SPLIT = r'\n(?=# -{3,})|\n(?=print\("\\n--- )'
SUBSECTION_STRIP = r"^# -{3,}[^\n]*\n?"


def _markdown(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {},
            "source": text.splitlines(keepends=True)}


def _code(text: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [], "source": text.rstrip().splitlines(keepends=True)}


def render(stem: str) -> dict:
    """Build one notebook from its .py source, as a dict. Writes nothing."""
    source = (NOTEBOOKS / f"{stem}.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    docstring = ast.get_docstring(tree)
    body = "\n".join(source.split("\n")[tree.body[1].lineno - 1:])

    marks = list(SECTION_BANNER.finditer(body))
    if not marks:
        raise RuntimeError(f"{stem}.py has no '# === A. Section ===' banners")

    setup = body[:marks[0].start()].strip().replace(
        "sys.path.insert(0, str(Path(__file__).resolve().parents[1]))",
        ROOT_FINDER,
    )

    cells = [_markdown(docstring.strip()), _code(setup)]
    for i, mark in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        section = body[mark.end():end].strip()
        cells.append(_markdown(f"## {mark.group(1).strip()}"))
        for part in re.split(SUBSECTION_SPLIT, "\n" + section):
            part = re.sub(SUBSECTION_STRIP, "", part).strip()
            if part:
                cells.append(_code(part))

    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python",
                           "name": "python3"},
            "language_info": {"name": "python", "version": "3.11"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }

    # Cell ids are the cell's position, written here directly.
    #
    # This used to call nbformat's normalize() when nbformat was
    # installed and skip ids when it was not. Three tools then disagreed
    # about the same file: a laptop with nbformat wrote RANDOM ids, CI
    # (no nbformat) regenerated with NO ids, and the nbstripout hook
    # rewrote them as "0", "1", ... on commit. The CI sync gate compared
    # the first two and could not pass, and every commit was rewritten
    # by the third.
    #
    # Positional ids are what nbstripout produces, so the hook now finds
    # nothing to change, and no optional package can alter the output.
    # Keys are sorted and the file ends in one newline because that is
    # the layout nbformat writes — again so the hook is a no-op.
    for i, cell in enumerate(cells):
        cell["id"] = str(i)
    return notebook


def build(stem: str) -> int:
    """Regenerate one notebook on disk. Returns its cell count."""
    notebook = render(stem)
    path = NOTEBOOKS / f"{stem}.ipynb"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(notebook, indent=1, ensure_ascii=False,
                           sort_keys=True) + "\n")
    return len(notebook["cells"])


def _content(notebook: dict) -> list[tuple[str, str]]:
    """What a notebook SAYS: each cell's type and source, nothing else."""
    return [(c.get("cell_type", ""), "".join(c.get("source", [])))
            for c in notebook.get("cells", [])]


def check(stem: str) -> str | None:
    """Whether the committed .ipynb matches its .py source. None if it does.

    Compares CONTENT — cell types and cell source — not bytes.

    The gate used to regenerate every notebook and fail on any byte of
    difference. But opening a notebook in Jupyter or VS Code rewrites its
    metadata block with the local kernel's name and Python version, and
    the commit hook strips outputs without touching that. So a notebook
    whose code was identical to its source failed the gate for recording
    that someone had opened it with a kernel called "base" on 3.13 — and
    the build stayed red on every push, with nothing actually stale.

    A check that fails on harmless differences gets ignored, and then it
    is not there on the day a notebook really has drifted. Kernel
    metadata is a fact about one machine; the cells are the notebook.
    """
    path = NOTEBOOKS / f"{stem}.ipynb"
    if not path.exists():
        return f"{stem}.ipynb does not exist"
    try:
        committed = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        return f"{stem}.ipynb is not valid JSON ({exc})"

    expected, actual = _content(render(stem)), _content(committed)
    if expected == actual:
        return None
    if len(expected) != len(actual):
        return (f"{stem}.ipynb has {len(actual)} cells, its source builds "
                f"{len(expected)}")
    first = next(i for i, (e, a) in enumerate(zip(expected, actual)) if e != a)
    return f"{stem}.ipynb differs from its source at cell {first}"


def main(argv: list[str]) -> int:
    args = argv[1:]
    checking = "--check" in args
    stems = ([a for a in args if a != "--check"]
             or sorted(p.stem for p in NOTEBOOKS.glob("*.py")))
    for stem in stems:
        if not (NOTEBOOKS / f"{stem}.py").exists():
            print(f"  {stem}: no such .py source")
            return 1

    if checking:
        problems = [p for p in (check(stem) for stem in stems) if p]
        for problem in problems:
            print(f"  STALE  {problem}")
        if problems:
            print("\n  Run `python scripts/build_notebooks.py` and commit the result.")
            return 1
        print(f"  {len(stems)} notebooks match their .py sources.")
        return 0

    for stem in stems:
        print(f"  {stem}: {build(stem)} cells")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
